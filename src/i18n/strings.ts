const STRINGS = { ru, en };

function resolve(dict: StringDict, path: string): StringValue | undefined {
  let node: StringValue | StringDict | undefined = dict;
  for (const part of path.split('.')) {
    if (node == null || typeof node !== 'object') return undefined;
    node = (node as StringDict)[part];
  }
  return node as StringValue | undefined;
}

export function getT(language: Language) {
  const dict = STRINGS[language];
  return function t(path: string, ...args: unknown[]): string {
    const value = resolve(dict, path);
    if (typeof value === 'function') return value(...args);
    if (typeof value === 'string') return value;
    return path;
  };
}

export function useT() {
  const { language } = useLanguage();
  return getT(language);
}

/** Translates an AuthError by its stable `code` when present, falling back
 * to the error's own message (an English message straight from Supabase
 * for the handful of error paths with no mapped code) so unmapped errors
 * still surface something instead of a blank screen. */
export function translateAuthError(e: { code?: string; message: string }, t: ReturnType<typeof getT>): string {
  if (e.code) return t(`authErrors.${e.code}`);
  return e.message;
}
